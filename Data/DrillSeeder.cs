// Seeds the built-in drill library (reference data). Runs at startup; only inserts when no
// built-in drills exist, so it never duplicates or clobbers custom drills on redeploy.
// Sport ids: 1=Soccer, 2=Basketball, 3=Volleyball, 4=Beach Volleyball, 5=Tennis.
public static class DrillSeeder
